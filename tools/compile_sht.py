"""Convert the unpacked th15 `.sht` self-machine reports into Lua definitions.

The unpacker emits one JSON per playable character under `th15_sht/`. Each JSON
carries the movement speeds, the hit and graze box sizes, the option positions
per power level and the shooter sets (the bullet sources each power level fires).
This tool lowers that into one Lua table per character so the replay can drive a
faithful player ship.

Usage:
    python tools/compile_sht.py <sht_dir> <out.lua>
"""
import io
import json
import os
import sys

PLAYER_NAMES = {
    "pl00": "reimu",
    "pl01": "marisa",
    "pl02": "sanae",
    "pl03": "reisen",
}


def pick(data, *names):
    for name in names:
        if name in data:
            return data[name]
    return None


def parse_options(data):
    """Return option positions per (focused, power level).

    The unpacker emits `option_pos` already grouped as
    { focused = { level = { {x,y}, ... } }, unfocused = ... }.
    """
    options = pick(data, "option_pos", "options")
    if not isinstance(options, dict):
        return None
    result = {}
    for mode, levels in options.items():
        if not isinstance(levels, dict):
            continue
        target = result.setdefault(mode, {})
        for level, points in levels.items():
            digits = "".join(ch for ch in str(level) if ch.isdigit())
            if not digits:
                continue
            parsed = []
            if isinstance(points, list):
                for point in points:
                    if isinstance(point, dict):
                        parsed.append([point.get("x", 0), point.get("y", 0)])
                    elif isinstance(point, (list, tuple)) and len(point) >= 2:
                        parsed.append([point[0], point[1]])
            target[int(digits)] = parsed
    return result


def parse_shooters(data):
    """Return the shooter sets, one per (kind, power level).

    The unpacker emits a list of entries with an index, a kind and a nested
    `shooters` list. Each shooter names its own offset, damage, angle, speed and
    animation, which is everything needed to fire a faithful volley.
    """
    sets = pick(data, "shooter_sets", "shooters", "sets")
    if not isinstance(sets, list):
        return None
    result = []
    for entry in sets:
        if not isinstance(entry, dict):
            continue
        sources = []
        for source in entry.get("shooters") or []:
            if not isinstance(source, dict):
                continue
            sources.append({
                "damage": source.get("dmg"),
                "offset_x": source.get("off_x", 0),
                "offset_y": source.get("off_y", 0),
                "angle": source.get("angle"),
                "speed": source.get("speed"),
                "fire": source.get("fire_rate"),
                "delay": source.get("start_delay"),
                "animation": source.get("anm"),
                "option": source.get("option"),
            })
        result.append({
            "index": entry.get("index"),
            "kind": entry.get("kind"),
            "sources": sources,
        })
    return result


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    sht_dir = sys.argv[1]
    out_path = sys.argv[2]

    lines = [
        "-- Generated by tools/compile_sht.py. Do not hand-edit.",
        "-- Source: %s" % sht_dir.replace("\\", "/"),
        "return {",
    ]
    count = 0
    for filename in sorted(os.listdir(sht_dir)):
        if not filename.endswith(".json"):
            continue
        key = filename[:-5]
        data = json.load(io.open(os.path.join(sht_dir, filename), encoding="utf-8"))
        character = PLAYER_NAMES.get(key, key)
        lines.append('    ["%s"] = {' % character)
        lines.append('        id = "%s",' % character)
        lines.append('        source = "%s",' % key)
        simple = {
            "hitbox": pick(data, "hitbox_u"),
            "grazebox": pick(data, "grazebox_u"),
            "itembox": pick(data, "itembox_u"),
            "move_unfocused": pick(data, "move_nf_str"),
            "move_focused": pick(data, "move_f_str"),
            "move_unfocused_diagonal": pick(data, "move_nf_dia"),
            "move_focused_diagonal": pick(data, "move_f_dia"),
            "power_levels": pick(data, "pwr_lvl_cnt"),
            "max_damage": pick(data, "max_dmg_u"),
        }
        for name, value in simple.items():
            if value is not None:
                lines.append("        %s = %s," % (name, value))
        options = parse_options(data)
        if options:
            lines.append("        options = {")
            for mode, levels in options.items():
                lines.append("            %s = {" % mode)
                for level in sorted(levels):
                    points = ", ".join("{ %s, %s }" % (p[0], p[1]) for p in levels[level])
                    lines.append("                [%d] = { %s }," % (level, points))
                lines.append("            },")
            lines.append("        },")
        shooters = parse_shooters(data)
        if shooters:
            lines.append("        shooters = {")
            for entry in shooters:
                kind = entry["kind"]
                kind_literal = 'nil' if kind is None else '"%s"' % kind
                lines.append("            { index = %s, kind = %s, sources = {"
                             % (entry["index"], kind_literal))
                for source in entry["sources"]:
                    parts = []
                    for field in ("damage", "offset_x", "offset_y", "angle",
                                  "speed", "fire", "delay", "animation", "option"):
                        if source.get(field) is not None:
                            parts.append("%s = %s" % (field, source[field]))
                    lines.append("                { %s }," % ", ".join(parts))
                lines.append("            } },")
            lines.append("        },")
        lines.append("    },")
        count += 1
    lines.append("}")
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d characters)" % (out_path, count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
