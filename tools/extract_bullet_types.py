"""Extract TH15 v1.00b's 44 bullet descriptors from the local executable.

Usage: python tools/extract_bullet_types.py th15.exe output.lua
Address and stride verified at shoot_one (0x41ae37); colour sprite selection
uses the descriptor's 16 colour records. No executable code is run.
"""
from pathlib import Path
import hashlib
import struct
import sys


def extract(path):
    data = Path(path).read_bytes()
    pe = struct.unpack_from('<I', data, 0x3c)[0]
    if data[pe:pe + 4] != b'PE\0\0':
        raise ValueError('Not a PE executable')
    sections = struct.unpack_from('<H', data, pe + 6)[0]
    opt_size = struct.unpack_from('<H', data, pe + 20)[0]
    base = struct.unpack_from('<I', data, pe + 24 + 28)[0]
    table_rva = 0x4e0f60 - base
    for i in range(sections):
        header = pe + 24 + opt_size + 40 * i
        size, rva, raw_size, raw = struct.unpack_from('<4I', data, header + 8)
        if rva <= table_rva and table_rva + 44 * 0x114 <= rva + raw_size:
            offset = raw + table_rva - rva
            break
    else:
        raise ValueError('Bullet table is outside the file-backed sections')
    result = []
    for kind in range(44):
        row = offset + kind * 0x114
        script = struct.unpack_from('<I', data, row)[0]
        sprites = [struct.unpack_from('<i', data, row + 4 + 16 * color)[0] for color in range(16)]
        radius = struct.unpack_from('<f', data, row + 0x104)[0]
        if not 0 < script < 400 or not 0 < radius < 32 or not all(-1 <= v < 579 for v in sprites):
            raise ValueError('Unrecognized TH15 bullet table layout')
        variants = [[struct.unpack_from('<i', data, row + 4 + 16 * color + 4 * field)[0]
                     for color in range(16)] for field in range(4)]
        result.append((script, sprites, radius, variants))
    if [v[0] for v in result[:5]] != [35, 36, 37, 38, 39]:
        raise ValueError('Expected TH15 v1.00b bullet table signature')
    return result, hashlib.sha256(data).hexdigest()


if __name__ == '__main__':
    rows, digest = extract(sys.argv[1])
    lines = ['-- Generated by tools/extract_bullet_types.py from TH15 v1.00b.',
             '-- Source SHA256: ' + digest, 'return {']
    for kind, (script, sprites, radius, variants) in enumerate(rows):
        lines.append('    [%d] = { script = %d, radius = %.8g, sprites = { %s }, variants = { %s } },' %
                     (kind, script, radius, ', '.join(map(str, sprites)),
                      ', '.join('{ ' + ', '.join(map(str, values)) + ' }' for values in variants)))
    lines.append('}')
    Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
