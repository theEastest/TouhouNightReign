"""Convert a thtk `thanm -l` specification into a Lua sprite/animation table.

`thanm -l` dumps the sprite rectangles and the animation scripts of an .anm
archive. Running that parser at game start is unnecessary, so this tool lowers
the text form into one Lua table per archive:

    {
      texture = "stgenm/stage01/enm1.png",
      sprites = { { x, y, w, h }, ... },          -- indexed from 1
      scripts = {
        [0] = { { id = 300, args = { 0 } }, ... }, -- instruction id + numeric args
      },
    }

Instruction ids follow anm version 8. See thtk thanm.c `formats_v8` for the
argument layout and the reference game decompilation for the mnemonic meaning.

Usage:
    python tools/compile_anm.py <spec_dir> <out.lua>
"""
import io
import os
import re
import sys


def parse_spec(path):
    entries = []
    current = None
    script = None
    with io.open(path, encoding="utf-8", errors="replace") as source:
        source_lines = source.readlines()
    for raw in source_lines:
        line = raw.rstrip("\n")
        if line.startswith("ENTRY #"):
            current = {"texture": None, "sprites": [], "scripts": {}}
            entries.append(current)
            script = None
            continue
        if current is None:
            continue
        if line.startswith("Name: "):
            current["texture"] = line[len("Name: "):].strip()
            continue
        offset = re.match(r"^(X-Offset|Y-Offset|LowResScale): (\d+)$", line)
        if offset:
            current[{"X-Offset": "offset_x", "Y-Offset": "offset_y", "LowResScale": "low_res_scale"}[offset[1]]] = int(offset[2])
            continue
        sprite = re.match(r"^Sprite: (\d+) (\d+)\*(\d+)\+(-?\d+)\+(-?\d+)$", line)
        if sprite:
            current["sprites"].append({
                "index": int(sprite.group(1)),
                "w": int(sprite.group(2)),
                "h": int(sprite.group(3)),
                "x": int(sprite.group(4)),
                "y": int(sprite.group(5)),
            })
            continue
        script_match = re.match(r"^Script: (\d+)$", line)
        if script_match:
            script = int(script_match.group(1))
            current["scripts"][script] = []
            continue
        instruction = re.match(r"^Instruction #\d+: (.+)$", line)
        if instruction and script is not None:
            tokens = instruction.group(1).split()
            if len(tokens) < 3:
                continue
            # Touhou Toolkit r12 dumps `<time> <param_mask> <type> <args...>`.
            # The opcode is the third field; the first two are the frame time
            # and the parameter mask.
            time_value = int(tokens[0])
            param_mask = int(tokens[1])
            opcode = int(tokens[2])
            args = []
            for token in tokens[3:]:
                token = token.rstrip("@")
                if token.endswith("f"):
                    try:
                        args.append(float(token[:-1]))
                        continue
                    except ValueError:
                        pass
                try:
                    args.append(int(token))
                except ValueError:
                    try:
                        args.append(float(token))
                    except ValueError:
                        args.append(token)
            current["scripts"][script].append({"time": time_value, "id": opcode, "mask": param_mask, "args": args})
    return entries


def lua_number(value):
    if isinstance(value, float):
        # Preserve small per-frame rates (e.g. st06wl +/-0.000033333334).
        # Rounding to six decimal places changes accumulated UV/angle motion.
        return repr(value)
    return str(value)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    spec_dir = sys.argv[1]
    out_path = sys.argv[2]

    files = sorted(f for f in os.listdir(spec_dir) if f.endswith(".txt"))
    lines = [
        "-- Generated by tools/compile_anm.py. Do not hand-edit.",
        "-- Source: %s" % spec_dir.replace("\\", "/"),
        "return {",
    ]
    total_sprites = 0
    total_scripts = 0
    for filename in files:
        archive = filename[:-4]
        entries = parse_spec(os.path.join(spec_dir, filename))
        if not entries:
            continue
        lines.append('    ["%s"] = {' % archive)
        for entry in entries:
            if not entry["texture"]:
                continue
            lines.append('        { texture = "%s",' % entry["texture"].replace("\\", "/"))
            lines.append("          offset_x = %d, offset_y = %d, low_res_scale = %d," %
                         (entry.get("offset_x", 0), entry.get("offset_y", 0), entry.get("low_res_scale", 0)))
            lines.append("          sprites = {")
            for sprite in entry["sprites"]:
                lines.append("            { x = %d, y = %d, w = %d, h = %d },"
                             % (sprite["x"], sprite["y"], sprite["w"], sprite["h"]))
            lines.append("          },")
            lines.append("          scripts = {")
            for script_id in sorted(entry["scripts"]):
                instructions = entry["scripts"][script_id]
                lines.append("            [%d] = {" % script_id)
                for instruction in instructions:
                    args = ", ".join(lua_number(a) for a in instruction["args"])
                    if args:
                        args = ", " + args
                    mask = ", mask = %d" % instruction["mask"] if instruction["mask"] else ""
                    lines.append("              { time = %d, id = %d%s%s },"
                                 % (instruction["time"], instruction["id"], mask, args))
                lines.append("            },")
                total_scripts += 1
            lines.append("          } },")
            total_sprites += len(entry["sprites"])
        lines.append("    },")
    lines.append("}")
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d sprites, %d scripts)" % (out_path, total_sprites, total_scripts))
    return 0


if __name__ == "__main__":
    sys.exit(main())
