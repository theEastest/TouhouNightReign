"""Derive the ascii sheet's glyph-to-sprite table.

The sheet is a 14x14 grid with a few blank slots inserted where a glyph was
unused. Rather than hard-code a fragile arithmetic rule, this tool walks the
grid, records which sprites are blank and emits the code-to-sprite map the HUD
font uses.

Usage:
    python tools/compile_ascii_font.py <ascii_png> <out.lua> [--sprites N]
"""
import io
import sys

try:
    from PIL import Image
except ImportError:
    print("Pillow is required")
    sys.exit(1)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    png_path = sys.argv[1]
    out_path = sys.argv[2]
    max_sprites = 290
    if "--sprites" in sys.argv:
        max_sprites = int(sys.argv[sys.argv.index("--sprites") + 1])

    image = Image.open(png_path).convert("RGBA")
    glyph = 14
    per_row = 18
    blanks = set()
    for index in range(1, max_sprites + 1):
        col = (index - 1) % per_row
        row = (index - 1) // per_row
        box = (col * glyph, row * glyph, col * glyph + glyph, row * glyph + glyph)
        if box[2] > image.width or box[3] > image.height:
            break
        cell = image.crop(box)
        if not any(pixel[3] > 16 for pixel in cell.getdata()):
            blanks.add(index)

    # Walk the codepoint range from 33 up, assigning the next non-blank sprite
    # to each character. The reference sheet covers the printable ASCII range.
    mapping = {}
    sprite = 1
    for code in range(33, 127):
        while sprite in blanks:
            sprite += 1
        if sprite > max_sprites:
            break
        mapping[code] = sprite
        sprite += 1

    lines = [
        "-- Generated by tools/compile_ascii_font.py. Do not hand-edit.",
        "-- Codepoint to sprite index for the HUD ascii sheet.",
        "return {",
    ]
    for code in sorted(mapping):
        character = chr(code)
        if character == '"':
            label = '\\"'
        elif character == "\\":
            label = "\\\\"
        else:
            label = character
        lines.append('    [%d] = %d, -- %s' % (code, mapping[code], label))
    lines.append("}")
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d glyphs, %d blank slots)" % (out_path, len(mapping), len(blanks)))
    for blank in sorted(blanks):
        print("  blank sprite: %d" % blank)
    return 0


if __name__ == "__main__":
    sys.exit(main())
