"""Compile thmsg text dumps without discarding timing or control instructions."""
from pathlib import Path
import json
import re
import sys


def parse(path):
    entries = {}
    current = None
    time = 0
    for raw in Path(path).read_text(encoding='utf-8-sig').splitlines():
        line = raw.strip()
        match = re.fullmatch(r'entry (\d+)(?: \(\d+\))?', line)
        if match:
            current = entries.setdefault(int(match[1]), [])
            time = 0
        elif line.startswith('@'):
            time = int(line[1:])
        elif current is not None and line:
            fields = line.split(';')
            opcode = int(fields[0])
            args = ([';'.join(fields[1:])] if opcode in (15, 16, 17) else
                    [float(v[:-1]) if v.endswith('f') else int(v) for v in fields[1:]])
            current.append(dict(time=time, id=opcode, args=args))
    return entries


def literal(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    return repr(value)


if __name__ == '__main__':
    lines = ['-- Generated by tools/compile_msg.py from local Chinese MSG dumps.', 'return {']
    for path in sorted(Path(sys.argv[1]).glob('st01?.txt')):
        lines.append('    ["%s"] = {' % path.stem)
        for entry, instructions in parse(path).items():
            lines.append('        [%d] = {' % entry)
            for ins in instructions:
                lines.append('            {time = %d, id = %d, %s},' %
                             (ins['time'], ins['id'], ', '.join(map(literal, ins['args']))))
            lines.append('        },')
        lines.append('    },')
    lines.append('}')
    Path(sys.argv[2]).write_text('\n'.join(lines) + '\n', encoding='utf-8')
