"""Convert a thtk `thstd -d` stage background config into a Lua table.

The .std file describes the scrolling background layers: each ENTRY names a
texture and a script, and lists the FACE placements that tile it across the
world. This tool lowers that into a form the stage background renderer walks.

Usage:
    python tools/compile_std.py <std_dir> <out.lua>
"""
import io
import os
import re
import sys


def parse_std(path):
    entries = []
    current = None
    for raw in io.open(path, encoding="utf-8", errors="replace"):
        line = raw.rstrip("\n")
        stripped = line.strip()
        if stripped.startswith("ENTRY:"):
            current = {"faces": []}
            entries.append(current)
            continue
        if current is None:
            continue
        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip()
        if key in ("Width", "Height") and value:
            current[key.lower()] = int(value)
        elif key == "Script_index":
            current["script"] = int(value)
        elif key == "Depth":
            current["depth"] = int(value)
        elif key == "FACE":
            parts = value.split()
            if len(parts) == 4:
                current["faces"].append({
                    "size": int(parts[0]),
                    "u": int(parts[1]),
                    "v": int(parts[2]),
                    "x": int(parts[3]),
                })
    return entries


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    std_dir = sys.argv[1]
    out_path = sys.argv[2]

    lines = [
        "-- Generated by tools/compile_std.py. Do not hand-edit.",
        "-- Source: %s" % std_dir.replace("\\", "/"),
        "return {",
    ]
    count = 0
    for filename in sorted(os.listdir(std_dir)):
        if not filename.endswith(".txt"):
            continue
        stage = filename[:-4]
        entries = parse_std(os.path.join(std_dir, filename))
        if not entries:
            continue
        lines.append('    ["%s"] = {' % stage)
        for entry in entries:
            faces = entry["faces"]
            if not faces:
                continue
            lines.append("        { width = %d, height = %d, depth = %d, script = %d,"
                         % (entry.get("width", 0), entry.get("height", 0),
                            entry.get("depth", 0), entry.get("script", 0)))
            lines.append("          faces = {")
            for face in faces:
                lines.append("            { size = %d, u = %d, v = %d, x = %d },"
                             % (face["size"], face["u"], face["v"], face["x"]))
            lines.append("          } },")
            count += 1
        lines.append("    },")
    lines.append("}")
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d entries)" % (out_path, count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
