"""Convert a thtk `thstd -d` stage background config into a Lua table.

The .std file describes the scrolling background layers: each ENTRY names a
texture and a script, and lists the FACE placements that tile it across the
world. This tool lowers that into a form the stage background renderer walks.

Usage:
    python tools/compile_std.py <std_dir> <out.lua>
"""
import io
import os
import re
import sys


def parse_std(path):
    entries = []
    current = None
    quad = None
    timeline = []
    in_script = False
    time = 0
    offset = 0
    with io.open(path, encoding="utf-8", errors="replace") as source:
        source_lines = source.readlines()
    for raw in source_lines:
        line = raw.rstrip("\n")
        stripped = line.strip()
        if stripped == "SCRIPT:":
            in_script = True
            continue
        if in_script:
            if re.fullmatch(r"\d+:", stripped):
                time = int(stripped[:-1])
            match = re.fullmatch(r"ins_(\d+)\((.*)\);", stripped)
            if match:
                args = []
                for value in match[2].split(","):
                    value = value.strip()
                    if value:
                        args.append(int(value[1:], 16) if value.startswith("#")
                                    else float(value[:-1]) if value.endswith("f")
                                    else int(value))
                timeline.append(dict(id=int(match[1]), time=time, offset=offset, args=args))
                offset += 8 + 4 * len(args)
            continue
        if stripped.startswith("ENTRY:"):
            current = {"faces": [], "quads": []}
            quad = None
            entries.append(current)
            continue
        if current is None:
            continue
        key, _, value = stripped.partition(":")
        key = key.strip()
        value = value.strip()
        if key == "QUAD":
            quad = {}
            current["quads"].append(quad)
            continue
        target = quad if quad is not None else current
        if key in ("Width", "Height") and value:
            target[key.lower()] = float(value)
        elif key == "Script_index":
            target["script"] = int(value)
        elif key == "Position":
            target["position"] = [float(v) for v in value.split()]
        elif key == "Type":
            target["type"] = int(value)
        elif key == "Depth":
            current["depth"] = float(value)
        elif key == "FACE":
            parts = value.split()
            if len(parts) == 4:
                current["faces"].append({
                    "flags": int(parts[0]),
                    "x": float(parts[1]),
                    "y": float(parts[2]),
                    "z": float(parts[3]),
                })
    return entries, timeline


def lua(value):
    if isinstance(value, dict):
        return "{ " + ", ".join(str(k) + " = " + lua(v) for k, v in value.items()) + " }"
    if isinstance(value, list):
        return "{ " + ", ".join(lua(v) for v in value) + " }"
    return repr(value)


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    std_dir = sys.argv[1]
    out_path = sys.argv[2]

    lines = [
        "-- Generated by tools/compile_std.py. Do not hand-edit.",
        "-- Source: %s" % std_dir.replace("\\", "/"),
        "return {",
    ]
    count = 0
    for filename in sorted(os.listdir(std_dir)):
        if not filename.endswith(".txt"):
            continue
        stage = filename[:-4]
        entries, timeline = parse_std(os.path.join(std_dir, filename))
        if not entries:
            continue
        lines.append('    ["%s"] = {' % stage)
        lines.append("        timeline = " + lua(timeline) + ",")
        for entry in entries:
            faces = entry["faces"]
            if not faces:
                continue
            # Keep the first script alias for older consumers; preserve every quad.
            entry["script"] = entry["quads"][0].get("script", 0) if entry["quads"] else 0
            lines.append("        " + lua(entry) + ",")
            count += 1
        lines.append("    },")
    lines.append("}")
    io.open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("wrote %s (%d entries)" % (out_path, count))
    return 0


if __name__ == "__main__":
    sys.exit(main())
