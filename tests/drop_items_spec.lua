local Plan = require("tnr.battle.drop_plan")
return function(eq, yes)
    local p = Plan.from_legacy({250, 3, 4})
    eq(p.money, 52, "existing coin quantities are preserved")
    eq(p.small_p, 6, "old score-point pool supplies small P")
    eq(p.large_p, 1, "large P is an eligible independent drop")
    local coin = Plan.from_legacy({7, 0, 0})
    eq(coin.money, 7, "coins still drop")
    eq(coin.small_p + coin.large_p, 0, "coins do not determine P quantity")
    local power = Plan.from_legacy({0, 0, 10})
    eq(power.money, 0, "P does not create coins")
    eq(power.small_p + power.large_p, 10, "previous point quantity is retained")
end
